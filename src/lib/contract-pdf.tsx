// ==================== เงินตรา + คำอ่านไทย ====================

function bahtWithWords(v?: string): string {
  const num = bahtNumber(v);
  if (!v || !v.trim()) return `${num} บาท (………………………………)`;
  return `${num} บาท (${bahtText(v)})`;
}

